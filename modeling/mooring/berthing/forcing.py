"""Immutable simulation-time forcing series (S2). Synthetic kinds are labeled synthetic; nothing is invented.

`ForcingSeries.at(t)` is a pure function of simulation time: it holds no cursor and no RNG state, so the
integrator may evaluate it at any RK4 stage time, in any order, in batch or interactive mode, and get
identical values. Absence of a channel in a replay is reported as unavailable, never as zero.
"""
import hashlib
import json
import math
import random
from datetime import timedelta

from mooring.core.schemas import (ForcingSpec, MotionCurrent, MotionEnvironment, MotionProvenance, MotionWaterLevel,
                                  MotionWind, Validity, ValidityReason)

EPS = 1e-9
CHANNELS = ("wind_speed_kt", "wind_gust_kt", "wind_from_true_deg", "current_speed_kt",
            "current_set_true_deg", "water_level_mllw_ft")
ANGLES = ("wind_from_true_deg", "current_set_true_deg")


class ForcingUncovered(ValueError):
    """Simulation time lies outside the forcing series coverage and the policy is `stop`."""


def _lerp(a, b, f): return a + (b-a)*f


def _lerp_angle(a, b, f):
    return (a + ((b-a+180) % 360 - 180)*f) % 360


class ForcingSeries:
    def __init__(self, spec: ForcingSpec, base_env, duration: float):
        self.spec, self.base, self.duration = spec, base_env.model_copy(deep=True), duration
        self.synthetic = spec.kind != "replay"
        if spec.kind == "replay":
            self.start, self.end = spec.samples[0].t_s, spec.samples[-1].t_s
            self.supplied = frozenset(n for n in CHANNELS if getattr(spec.samples[0], n) is not None)
        else:
            self.start, self.end = 0.0, duration
            self.supplied = frozenset(CHANNELS)
        self.knots = ()
        if spec.kind == "gusts":
            rng = random.Random(spec.seed)
            n = math.ceil(duration/spec.gust_correlation_s)+2
            self.knots = (0.0,)+tuple(rng.gauss(0, spec.gust_sigma_kt) for _ in range(n-1))
        material = {"spec": spec.model_dump(mode="json"), "duration_s": duration,
                    "base": base_env.model_dump(mode="json", exclude={"valid_at_utc"})}
        text = json.dumps(material, sort_keys=True, separators=(",", ":"))
        self.revision = "frc-"+hashlib.sha256(text.encode()).hexdigest()[:12]

    def covered(self, t): return self.start-EPS <= t <= self.end+EPS

    def at(self, t):
        """(EnvironmentSnapshot, covered) at simulation time t. Raises ForcingUncovered per policy."""
        covered = self.covered(t)
        if not covered and (self.spec.on_uncovered == "stop" or t < self.start):
            raise ForcingUncovered(f"forcing series {self.revision} covers t={self.start:g}..{self.end:g} s; "
                                   f"simulation time {t:g} s is outside it (policy: {self.spec.on_uncovered})")
        tc = min(max(t, self.start), self.end)
        v = {n: getattr(self.base, n) for n in CHANNELS}
        k = self.spec.kind
        if k == "ramp":
            tgt, t0 = self.spec.target, self.spec.ramp_start_s
            f = min(1.0, max(0.0, (tc-t0)/(tgt.t_s-t0)))
            for n in CHANNELS:
                goal = getattr(tgt, n)
                if goal is not None:
                    v[n] = _lerp_angle(v[n], goal, f) if n in ANGLES else _lerp(v[n], goal, f)
        elif k == "gusts":
            h = self.spec.gust_correlation_s
            i = min(int(tc//h), len(self.knots)-2)
            g = _lerp(self.knots[i], self.knots[i+1], tc/h-i)
            v["wind_speed_kt"] = max(0.0, v["wind_speed_kt"]+g)
            v["wind_gust_kt"] = max(v["wind_speed_kt"], v["wind_gust_kt"]+g)
        elif k == "replay":
            s = self.spec.samples
            lo, hi = 0, len(s)-1
            while hi-lo > 1:
                mid = (lo+hi)//2
                lo, hi = (mid, hi) if s[mid].t_s <= tc else (lo, mid)
            f = (tc-s[lo].t_s)/(s[hi].t_s-s[lo].t_s)
            for n in self.supplied:
                a, b = getattr(s[lo], n), getattr(s[hi], n)
                v[n] = _lerp_angle(a, b, f) if n in ANGLES else _lerp(a, b, f)
        if self.spec.tide_amplitude_ft:
            w, ph = 2*math.pi/self.spec.tide_period_s, self.spec.tide_phase_rad
            # Zero at t=0, so lines installed at the scenario water level start unstrained by the tide term.
            v["water_level_mllw_ft"] += self.spec.tide_amplitude_ft*(math.sin(w*tc+ph)-math.sin(ph))
        v["wind_gust_kt"] = max(v["wind_gust_kt"], v["wind_speed_kt"])
        v["valid_at_utc"] = self.base.valid_at_utc+timedelta(seconds=t)
        return self.base.model_copy(update=v), covered

    def provenance(self):
        if self.synthetic:
            return MotionProvenance(kind="mock", source=f"synthetic forcing: {self.spec.kind}",
                notes=[f"forcing revision {self.revision}", "Generated by the simulator; not an observation or forecast."]
                      + ([f"seed {self.spec.seed}"] if self.spec.seed is not None else []))
        return MotionProvenance(kind="unknown", source="supplied replay samples",
                                notes=[f"forcing revision {self.revision}", "Origin and accuracy of the supplied samples are not verified."])

    def motion_environment(self, env, t, covered=True):
        """rm0 environment-at-t. Channels the series does not supply are unavailable (values absent), not zero."""
        prov = self.provenance()
        code = "FORCING_SYNTHETIC" if self.synthetic else "FORCING_SUPPLIED_UNVERIFIED"
        reasons = [ValidityReason(code=code, message=prov.source)]
        if not covered:
            reasons.append(ValidityReason(code="FORCING_UNCOVERED", message="Held at the last covered value; run is invalid."))
        validity = Validity(state="invalid" if not covered else "limited", reasons=reasons)

        def part(cls, names, **vals):
            if all(n in self.supplied for n in names):
                return cls(availability="available", provenance=prov, validity=validity, **vals)
            return cls(availability="unavailable", provenance=MotionProvenance(kind="unknown", source="not in forcing series",
                notes=["Scenario base value was used by the physics for this channel."]), validity=Validity(state="unknown"))
        return MotionEnvironment(t_s=t, valid_at_utc=env.valid_at_utc,
            wind=part(MotionWind, ("wind_speed_kt", "wind_gust_kt", "wind_from_true_deg"),
                      speed_kt=env.wind_speed_kt, gust_kt=env.wind_gust_kt, from_true_deg=env.wind_from_true_deg),
            current=part(MotionCurrent, ("current_speed_kt", "current_set_true_deg"),
                         speed_kt=env.current_speed_kt, set_true_deg=env.current_set_true_deg),
            water=part(MotionWaterLevel, ("water_level_mllw_ft",), level_mllw_ft=env.water_level_mllw_ft))


def apparent_wind(env, heading_true_deg, u_fps, v_fps):
    """Wind relative to the moving hull. u forward, v port (ft/s); returns an updated snapshot.

    Only wind is made relative: current drag on a moving hull is carried by the body damping term, so making the
    current relative as well would count that damping twice.
    """
    kt = 1/1.6878098571
    h = math.radians(heading_true_deg)
    ve = (u_fps*math.sin(h)-v_fps*math.cos(h))*kt   # east, knots
    vn = (u_fps*math.cos(h)+v_fps*math.sin(h))*kt
    f = math.radians(env.wind_from_true_deg)
    we, wn = -env.wind_speed_kt*math.sin(f), -env.wind_speed_kt*math.cos(f)   # velocity the air moves toward
    ae, an = we-ve, wn-vn
    speed = math.hypot(ae, an)
    frm = env.wind_from_true_deg if speed < 1e-12 else math.degrees(math.atan2(-ae, -an)) % 360
    return env.model_copy(update={"wind_speed_kt": speed, "wind_from_true_deg": frm,
                                  "wind_gust_kt": max(speed, env.wind_gust_kt+(speed-env.wind_speed_kt))})
