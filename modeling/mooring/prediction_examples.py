"""S7 display fixtures: an authored MOCK prediction request and response, never outputs of the predictor.

The response geometry is generated by simple kinematics (constant-rate turn in a flat local plane) so the UI can build
the backup-camera overlay before the service exists. Loads, dynamics and hazards are not computed; every value is
labeled MOCK. Deterministic: fixed times, ids and no random numbers.
"""

import math
from datetime import UTC, datetime, timedelta

from mooring.core.schemas import PredictionRequest, PredictionResponse

T0 = datetime(2026, 11, 5, 15, 0, tzinfo=UTC)
LAT0, LON0 = 36.9560, -76.3260          # Hampton Roads, approaching the NAVSTA Norfolk piers (illustrative)
FT_PER_DEG_LAT = 364_000.0
FT_PER_DEG_LON = FT_PER_DEG_LAT * math.cos(math.radians(LAT0))
LENGTH_FT, BEAM_FT = 505.0, 66.0         # DDG 51 nominal; footprint is a parametric planform


def _geo(x_east_ft: float, y_north_ft: float) -> dict:
    return {"lat": round(LAT0 + y_north_ft / FT_PER_DEG_LAT, 7), "lon": round(LON0 + x_east_ft / FT_PER_DEG_LON, 7)}


def _footprint(x: float, y: float, heading_deg: float) -> list[dict]:
    half_l, half_b = LENGTH_FT / 2, BEAM_FT / 2
    local = [(-half_l, -half_b), (0.3 * LENGTH_FT, -half_b), (half_l, 0.0), (0.3 * LENGTH_FT, half_b), (-half_l, half_b)]
    h = math.radians(heading_deg)
    # Ship +x forward, +y port; heading clockwise from north. East/north of a ship-local point:
    out = []
    for fx, fy in local:
        east = x + fx * math.sin(h) - fy * math.cos(h)
        north = y + fx * math.cos(h) + fy * math.sin(h)
        out.append(_geo(east, north))
    return out


def _ticks(turn_degps: float, speed_kt: float, rudder: float, horizon_s: int = 300, tick_s: int = 10,
           spread: bool = False) -> list[dict]:
    x = y = 0.0
    heading = 200.0
    speed_fps = speed_kt * 1.6878
    ticks = []
    for i in range(horizon_s // tick_s + 1):
        t = i * tick_s
        if i:
            for _ in range(tick_s * 10):
                heading = (heading - turn_degps * 0.1) % 360      # + yaw rate (to port) lowers the true heading
                x += speed_fps * 0.1 * math.sin(math.radians(heading))
                y += speed_fps * 0.1 * math.cos(math.radians(heading))
        ticks.append({
            "t_s": t, "t_utc": (T0 + timedelta(seconds=t)).isoformat(), "position": _geo(x, y),
            "heading_true_deg": round(heading, 3), "sog_kt": speed_kt, "cog_true_deg": round(heading, 3),
            "rudder_deg": rudder, "engine_order": 0.25, "footprint": _footprint(x, y, heading),
            **({"position_sd_ft": round(15 + 0.25 * t, 1)} if spread else {}),
        })
    return ticks


def _corridor(ticks: list[dict]) -> list[dict]:
    """Illustrative corridor: the path offset sideways by a widening margin (not a percentile envelope)."""
    left, right = [], []
    for tick in ticks:
        lat, lon = tick["position"]["lat"], tick["position"]["lon"]
        x, y = (lon - LON0) * FT_PER_DEG_LON, (lat - LAT0) * FT_PER_DEG_LAT
        h = math.radians(tick["heading_true_deg"])
        w = BEAM_FT / 2 + tick.get("position_sd_ft", 0) * 1.64
        left.append(_geo(x - w * math.cos(h), y + w * math.sin(h)))
        right.append(_geo(x + w * math.cos(h), y - w * math.sin(h)))
    return left + right[::-1]


def _mock_validity(component: str) -> dict:
    return {"state": "limited", "reasons": [{"code": "AUTHORED_DISPLAY_FIXTURE",
            "message": "MOCK: authored kinematics for UI development; no dynamics, loads or hazard data.",
            "affected_components": [component]}]}


def build() -> dict[str, dict]:
    request = PredictionRequest.model_validate({
        "vessel": {"vessel_id": "DDG-51-demo", "ship_class_id": "DDG-51-FIIA", "observed_utc": (T0 - timedelta(seconds=2)).isoformat(),
                   "position": {"lat": LAT0, "lon": LON0}, "heading_true_deg": 200, "surge_kt": 6.0, "rudder_deg": 5,
                   "engine_order": 0.25, "uncertainty": {"position_sd_ft": 15, "heading_sd_deg": 1, "speed_sd_kt": 0.2},
                   "source": "gps+gyro"},
        "as_of_utc": T0.isoformat(), "horizon_s": 300, "tick_s": 10,
        "alternatives": [{"alt_id": "more-rudder", "label": "Rudder 15 to port now",
                          "helm_commands": [{"t_s": 0, "rudder_deg": 15}]},
                         {"alt_id": "tug-push", "label": "Tug pushes to starboard at the port shoulder",
                          "tug_commands": [{"t_s": 0, "tug_id": "T1", "point": "port_shoulder",
                                            "force_lbf": 30000, "direction_rel_deg": 90}]}],
        "uncertainty": {"samples": 32, "seed": 7},
        "hazards": {"berth_id": "NAVSTA-NORFOLK-P12-N", "coastline": True, "min_clearance_ft": 50},
    })
    hold = _ticks(0.15, 6.0, 5, spread=True)
    rudder = _ticks(0.45, 5.6, 15, spread=True)
    push = _ticks(-0.05, 6.0, 5, spread=True)
    approach = {"t_s": 240, "kind": "pier", "element_id": "NAVSTA-NORFOLK-P12-N:face", "clearance_ft": 35.0,
                "position": hold[24]["position"], "probability": 0.41}
    response = PredictionResponse.model_validate({
        "result_id": "res_prediction_fixture", "model": "mooring.prediction (MOCK fixture)", "model_version": "fixture",
        "backend": "mock", "inputs_hash": "sha256:fixture", "computed_at_utc": T0.isoformat(), "status": "AMBER",
        "assumptions": ["MOCK display fixture: authored constant-rate turns, not a dynamics prediction."],
        "validity": _mock_validity("prediction"),
        "result": {
            "vessel_id": "DDG-51-demo", "engine": "transit", "as_of_utc": T0.isoformat(), "input_age_s": 2.0,
            "hazards_checked": ["pier", "fender"],
            "alternatives": [
                {"alt_id": "hold", "label": "Hold current commands", "ticks": hold, "corridor": _corridor(hold),
                 "closest_approach": approach, "first_breach": approach},
                {"alt_id": "more-rudder", "label": "Rudder 15 to port now", "ticks": rudder, "corridor": _corridor(rudder),
                 "closest_approach": {**approach, "t_s": 300, "clearance_ft": 180.0, "position": rudder[-1]["position"],
                                      "probability": 0.0}},
                {"alt_id": "tug-push", "label": "Tug pushes to starboard at the port shoulder", "ticks": push,
                 "corridor": _corridor(push)},
            ],
        },
    })
    return {"predict_trajectory_request": request.model_dump(mode="json"),
            "predict_trajectory_response": response.model_dump(mode="json")}


PREDICTION_EXAMPLES = build()
