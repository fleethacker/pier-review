"""S7 contract examples: a stored output of the REAL prediction engine from the recorded NOAA CO-OPS snapshot.

The example is generated by `scripts/regen_prediction_example.py` and committed under
`mooring/prediction/fixtures/example/`. It is stored rather than recomputed at contract export because floating-point
results differ slightly across platforms (macOS vs. the Linux CI runner), which would make the byte-exact contract
check flaky. `test_s7_example_matches_engine` re-runs the engine and requires agreement within a small tolerance, so
the stored example cannot drift from the physics unnoticed.
"""

import json
from pathlib import Path

EXAMPLE_DIR = Path(__file__).parent / "prediction" / "fixtures" / "example"


def build() -> dict[str, dict]:
    return {"predict_trajectory_request": json.loads((EXAMPLE_DIR / "request.json").read_text()),
            "predict_trajectory_response": json.loads((EXAMPLE_DIR / "response.json").read_text())}


def generate() -> dict[str, dict]:
    """Recompute the example with the engine (used by the regeneration script and the drift test)."""
    from mooring.prediction import engine, presets
    request = presets.approach_request()
    response = engine.predict(request)
    response = response.model_copy(update={"result_id": "res_prediction_example", "computed_at_utc": presets.AS_OF})
    return {"predict_trajectory_request": request.model_dump(mode="json"),
            "predict_trajectory_response": response.model_dump(mode="json")}


PREDICTION_EXAMPLES = build()
